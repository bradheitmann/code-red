import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = new URL('../../skills/code-red/', import.meta.url);
async function collect(relative = ''): Promise<string[]> {
  const entries = await readdir(new URL(relative, root), { withFileTypes: true });
  const paths = await Promise.all(entries.map(async (entry) => {
    const path = relative + entry.name;
    if (entry.isDirectory()) return collect(path + '/');
    return entry.isFile() && entry.name.endsWith('.md') ? [path] : [];
  }));
  return paths.flat().sort();
}
const documents = await Promise.all((await collect()).map(async (path) => {
  const text = await readFile(new URL(path, root), 'utf8');
  return { path, uri: `code-red://skill/${path}`, text, sha256: createHash('sha256').update(text).digest('hex') };
}));
if (!documents.some((document) => document.path === 'SKILL.md')) throw new Error('Canonical SKILL.md is required');
const target = new URL('../generated/content.ts', import.meta.url);
await mkdir(new URL('./', target), { recursive: true });
await writeFile(target, '// Generated by server/scripts/bundle-content.ts; edit skills/code-red instead.\nexport const documents = ' + JSON.stringify(documents, null, 2) + ' as const;\n');
console.log(`Bundled ${documents.length} canonical Markdown documents into ${fileURLToPath(target).split('/').slice(-3).join('/')}`);
